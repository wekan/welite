"""Regenerate the Pascal Unicode case-fold table from Python's Unicode data."""
from pathlib import Path
from unicodedata import unidata_version

output = Path(__file__).resolve().parents[1] / 'src' / 'wlfold.inc'
pairs = [(code, char.casefold()) for code in range(0x110000)
         if (char := chr(code)).casefold() != char]
with output.open('w', encoding='ascii', newline='\n') as table:
    table.write(f'{{ Unicode {unidata_version} default full case fold. Generated by releases/genfold.py. }}\n')
    table.write(f'const FoldMap: array[0..{len(pairs) - 1}] of TFoldEntry = (\n')
    for index, (code, folded) in enumerate(pairs):
        literal = ''.join(f'#${byte:02X}' for byte in folded.encode())
        suffix = ',' if index + 1 < len(pairs) else ');'
        table.write(f'  (Code:${code:X}; Folded:{literal}){suffix}\n')
