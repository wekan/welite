#!/usr/bin/env python3
"""Write src/tpl/cardset.inc from Weddy's card_settings.json: WeKan's Card
Settings table (models/lib/cardSettingsRows.js and cardSettingsSections.js,
as Weddy's cmd/card-settings/generate.cjs writes it), as one Pascal string
that src/wlcardst.pas parses.

    python3 -I releases/gencardst.py ../caddy-wekan-plugin/web/card_settings.json
"""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1])
data = json.loads(src.read_text(encoding='utf-8'))
text = json.dumps(data, ensure_ascii=True, separators=(',', ':'))
parts = [text[i:i + 200] for i in range(0, len(text), 200)]
lines = ['{ Generated by releases/gencardst.py from Weddy\'s card_settings.json: do not edit. }',
         'const CARD_SETTINGS_JSON: string =']
lines += ["  '" + p.replace("'", "''") + "'" + (' +' if i < len(parts) - 1 else ';') for i, p in enumerate(parts)]
out = Path(__file__).resolve().parent.parent / 'src/tpl/cardset.inc'
out.write_text('\n'.join(lines) + '\n')
print(out, len(text))
