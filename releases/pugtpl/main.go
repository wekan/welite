// pugtpl: one of Weddy's Pug templates (caddy-wekan-plugin/web/templates)
// as a Pascal include for src/wltpl.pas - the Go html/template text Weddy's
// own Pug library (Joker/jade) makes of it, as one string constant.
//
//	go run ./releases/pugtpl NAME weddy/web/templates/NAME.pug > src/tpl/NAME.inc
//
// Bytes outside printable ASCII are written as #$xx, so the include is the
// same text whatever the compiler's code page.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/Joker/jade"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: pugtpl NAME FILE.pug")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[2])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	text, err := jade.Parse(os.Args[1], src)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by releases/pugtpl from Weddy's %s.pug - do not edit.\n", os.Args[1])
	fmt.Fprintf(&b, "const TPL_%s =\n", strings.ToUpper(os.Args[1]))
	line, quoted := 0, false
	// brk ends the line every hundred or so characters, the string closed
	// before the + and opened again after it.
	brk := func() {
		if line <= 100 {
			return
		}
		if quoted {
			b.WriteString("' +\n'")
		} else {
			b.WriteString(" +\n")
		}
		line = 0
	}
	for i := 0; i < len(text); i++ {
		brk()
		c := text[i]
		if c >= 32 && c < 127 {
			if !quoted {
				b.WriteString("'")
				quoted = true
			}
			if c == '\'' {
				b.WriteString("''")
			} else {
				b.WriteByte(c)
			}
			line++
			continue
		}
		if quoted {
			b.WriteString("'")
			quoted = false
		}
		fmt.Fprintf(&b, "#$%02x", c)
		line += 4
	}
	if quoted {
		b.WriteString("'")
	}
	if len(text) == 0 {
		b.WriteString("''")
	}
	b.WriteString(";\n")
	os.Stdout.WriteString(b.String())
}
