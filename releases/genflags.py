#!/usr/bin/env python3
"""Generate src/wlflags.inc - WeKan's language flags (imports/i18n/languageFlags.js:
the flag of each language, the tags whose flag or country flag is not the
rule's, and the region codes drawn as a country flag) - for the HTML5 view's
changeLanguagePopup (src/wlflag.pas).

    python3 -I releases/genflags.py ../../../imports/i18n/languageFlags.js
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text(encoding='utf-8')


def table(name):
    body = re.search(r'const ' + name + r' = \{(.*?)\};', src, re.S).group(1)
    return sorted(re.findall(r"'([^']+)':\s*'([^']+)'", body))


flags = table('flagMap')
languages = table('languageOverrides')
countries = table('countryOverrides')
codes = re.search(r"new Set\('([A-Z ]+)'\.split", src).group(1).split()
assert len(flags) > 150 and languages and countries and len(codes) > 20, (len(flags), len(codes))


def text(s):
    return ''.join('#$%02x' % b for b in s.encode('utf-8'))


def pair(name, rows):
    n = len(rows)
    out = ['  %s_COUNT = %d;' % (name, n), '  %s_KEYS: array[0..%s_COUNT - 1] of string = (' % (name, name)]
    out += ["    '%s'%s" % (k, ',' if i < n - 1 else ');') for i, (k, _) in enumerate(rows)]
    out += ['  %s_FLAGS: array[0..%s_COUNT - 1] of string = (' % (name, name)]
    out += ['    %s%s' % (text(v), ',' if i < n - 1 else ');') for i, (_, v) in enumerate(rows)]
    return out


out = ['{ Generated by releases/genflags.py from WeKan\'s imports/i18n/languageFlags.js.',
       '  Do not edit; generate it again. Each table is sorted by its key. }', 'const']
out += pair('LANGUAGE_FLAG', flags) + pair('TAG_LANGUAGE_FLAG', languages) + pair('TAG_COUNTRY_FLAG', countries)
out += ["  // The region codes whose country flag is the region's own.", "  FLAG_REGIONS = ' %s ';" % ' '.join(codes), '']
Path(__file__).resolve().parent.parent.joinpath('src/wlflags.inc').write_text('\n'.join(out), encoding='utf-8')
print(len(flags), 'languages,', len(languages) + len(countries), 'tags,', len(codes), 'regions')
