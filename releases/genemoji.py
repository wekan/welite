#!/usr/bin/env python3
"""Generate src/wlemoji.inc - markdown-it-emoji's full set of :shortcodes:,
the emoji WeKan's Markdown writes for each - from Weddy's generated copy of
it (caddy-wekan-plugin/web/emoji_data.go, from markdown-it-emoji 3.1.0's
lib/data/full.mjs, MIT).

    python3 -I releases/genemoji.py ../caddy-wekan-plugin/web/emoji_data.go
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text(encoding='utf-8')
licence = src.split('package web', 1)[0].strip().splitlines()
pairs = sorted(set(re.findall(r'^\t"([^"]+)":\s+"([^"]+)",$', src, re.M)))
assert len(pairs) > 1000, len(pairs)
out = ['{ Generated by releases/genemoji.py from markdown-it-emoji 3.1.0\'s full set.', '  Do not edit; generate it again.', '']
out += ['  ' + l[2:].strip() if l.startswith('//') else '' for l in licence[2:]]
out += ['}', 'const', '  EMOJI_COUNT = %d;' % len(pairs), '  // Sorted by shortcode, for a binary search.',
        '  EMOJI_CODES: array[0..EMOJI_COUNT - 1] of string = (']
out += ['    %s%s' % ("'" + c.replace("'", "''") + "'", ',' if i < len(pairs) - 1 else ');') for i, (c, _) in enumerate(pairs)]
out += ['  EMOJI_CHARS: array[0..EMOJI_COUNT - 1] of string = (']
for i, (_, e) in enumerate(pairs):
    b = e.encode('utf-8')
    out.append('    %s%s' % (''.join('#$%02x' % x for x in b), ',' if i < len(pairs) - 1 else ');'))
out.append('')
Path(__file__).resolve().parent.parent.joinpath('src/wlemoji.inc').write_text('\n'.join(out), encoding='utf-8')
print(len(pairs), 'shortcodes')
